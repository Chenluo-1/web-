def title_for(leaf, index):
    """按叶子类目取成型标题；同类目商品多于标题条数时补序号，避免重名。"""
    pool = TITLE_POOLS.get(leaf)
    if not pool:
        return None
    title = pool[index % len(pool)]
    if index >= len(pool):
        title = "%s 第 %d 批" % (title, index // len(pool) + 1)
    return title


# 兼容旧调用（曾专用于美食）
def food_title(leaf, index):
    return title_for(leaf, index)


